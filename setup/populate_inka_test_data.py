def populate_sheet(sheets_client: GoogleSheetsClient, sheet_name: str, data: list, sheet_type: str = "regular") -> bool:
    """Заполнить лист данными"""
    try:
        logger.info(f"📝 Заполнение листа '{sheet_name}'...")
        
        count = 0
        for row in data:
            if sheets_client.append_row(sheet_name, row):
                count += 1
        
        logger.info(f"✅ Добавлено {count} записей в '{sheet_name}'")
        return True
    except Exception as e:
        logger.error(f"❌ Ошибка при заполнении '{sheet_name}': {e}")
        return False

